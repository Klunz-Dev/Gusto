def choice_quote(cat: str) -> list[str]:
    # 1. Фильтруем общий список, оставляя только цитаты с нужной категорией
    filtered_quotes = [q for q in quote_json if q["category"] == cat]
    
    # Проверяем, нашлись ли цитаты для такой категории
    if not filtered_quotes:
        print(f"Категория '{cat}' не найдена.")
        return
        
    # 2. Выбираем случайную цитату из отфильтрованного списка
    quote = random.choice(filtered_quotes)
    
    # Красиво печатаем результат
    print(f"«{quote['text']}» — {quote['author']}")

    return quote["text"], quote["author"]
